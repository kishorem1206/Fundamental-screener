def get_metric(metric_id: str) -> MetricDefinition | None:
    """Look up one metric's canonical definition, or None if unregistered."""
    return METRIC_REGISTRY.get(metric_id)


def metrics_for_sector(sector_name: str) -> list[MetricDefinition]:
    """Every registered metric applicable to one sector (by sector_name, e.g. "Banks").
    Order matches METRIC_REGISTRY's (alphabetical by id), not any scoring weight."""
    return [m for m in METRIC_REGISTRY.values() if sector_name in m.applicable_sectors]
