"""Canonical metric registry — Architecture v2 upgrade, Stage 0.

Catalogs every metric_id already in use across the 34 sector frameworks
(app/sectors/*.py's SectorMetric declarations) plus the operational metrics
ingested straight into the provenance ledger (app/ingestion/banking_ingestion.py,
annual_report_ingestion.py) — generated by walking those files' ASTs, not
hand-typed, so it reflects what the app actually uses today rather than an
aspirational list.

Purely additive at this stage: nothing reads from this registry yet — no sector
file, ingestion file, or API response changes. It exists so later stages (MCP
tool schemas, the declarative screening engine, sector-config-as-YAML) have a
single stable metric_id -> label/unit/category mapping to build on, instead of
re-deriving one from scratch or inventing a second, inconsistent naming scheme.

`applicable_sectors` lists the exact `sector_name` strings used by
app/sectors/registry.py's get_framework() (e.g. "Banks", "NBFCs") — not file
names or sub-types, so a later caller can filter directly against what
get_framework().sector_name actually returns.
"""
